-- ── Step 1：用比较运算符筛选行 ──────────────────────────────────────────────

-- 【查询 1】WHERE：只保留月薪 30000 及以上的行。>= 含等于，> 不含
-- 预期：9 行 3 列：王振华 技术总监 45000、王强 高级工程师 32000、郑浩 产品总监 40000、秦悦 财务总监 32000
SELECT name, title, salary FROM employees WHERE salary >= 30000;

-- 【查询 2】TODO：用 AND 把两个条件合在一起——只看研发部（dept_id = 1）里月薪 30000 及以上的员工，
--               查出 name、dept_id、title、salary 四列
-- 预期：5 行 4 列：王振华 1 技术总监 45000、陈雅婷 1 高级工程师 31000、刘洋 1 高级工程师 30000

-- 【查询 3】OR：满足任意一个就保留（OR 的优先级比 AND 低，两者混用时要加括号）
-- 预期：7 行 2 列：马婧 4、唐磊 4、范斌 5、袁浩然 5
SELECT name, dept_id FROM employees WHERE dept_id = 4 OR dept_id = 5;

-- 【查询 4】TODO：查出 2022-01-01 及以后入职、且不在市场部（dept_id <> 3）的员工的 name、hire_date、salary。
--               日期存成 'YYYY-MM-DD' 文本，按文本比较大小就是比较先后，所以可以直接用 >=
-- 预期：3 行 3 列：吴桐 2022-07-11 14000、徐嘉明 2024-02-13 13000、唐磊 2022-04-25 11000

-- 【查询 5】NULL 不等于 0，也不是空字符串。判断「为空」要用 IS NULL，写 = NULL 永远匹配不到
-- 预期：5 行 2 列：王振华 技术总监、郑浩 产品总监、谢雨欣 市场总监、马婧 人事总监、秦悦 财务总监
SELECT name, title FROM employees WHERE manager_id IS NULL;

