-- 预期：30 行 4 列：王振华 1 技术总监 45000、李思远 1 架构师 38000、王强 1 高级工程师 32000、郑浩 2 产品总监 40000

-- 【查询 13】排序键有并列时先后不确定，再补一个 id 兜底，结果才稳定
-- 预期：6 行 2 列：王振华 45000、郑浩 40000、李思远 38000、谢雨欣 36000、王强 32000、秦悦 32000
SELECT name, salary FROM employees ORDER BY salary DESC, id LIMIT 6;
