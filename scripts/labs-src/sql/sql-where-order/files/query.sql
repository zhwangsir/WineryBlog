--                提示：_ 匹配恰好 1 个字符，% 匹配任意多个字符（包括 0 个）
-- 预期：3 行 2 列：王振华 技术总监、王强 高级工程师、王凯 市场专员

-- 【查询 11】% 放在前面：以「工程师」结尾的职位都算，高级、初级、测试工程师也包含在内
-- 预期：10 行 2 列：王强 高级工程师、黄敏 工程师、吴桐 初级工程师、苏晴 测试工程师
SELECT name, title FROM employees WHERE title LIKE '%工程师';

