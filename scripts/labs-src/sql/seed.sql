-- ----------------------------------------------------------------------------
-- 项目表：8 个项目
-- budget 是项目预算（万元）；end_date 为 NULL 表示还没有确定的结束时间；
-- status 取值：进行中 / 已完成 / 已搁置。注意 8 号项目已搁置，还没有任何人被分派进去
-- ----------------------------------------------------------------------------
CREATE TABLE projects (
    id          INTEGER PRIMARY KEY,                          -- 项目编号
    name        TEXT    NOT NULL UNIQUE,                      -- 项目名称
    dept_id     INTEGER NOT NULL REFERENCES departments(id),  -- 归属部门
    lead_id     INTEGER REFERENCES employees(id),             -- 项目负责人的员工编号
    budget      REAL    NOT NULL,                             -- 预算（万元）
    start_date  TEXT    NOT NULL,                             -- 开始日期
    end_date    TEXT,                                         -- 计划结束日期
    status      TEXT    NOT NULL CHECK (status IN ('进行中', '已完成', '已搁置'))
);

