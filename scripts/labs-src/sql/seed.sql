-- ----------------------------------------------------------------------------
-- 员工表：30 名员工
-- salary 是月薪（元）；manager_id 是直属上级的员工编号，5 位总监没有上级，为 NULL
-- ----------------------------------------------------------------------------
CREATE TABLE employees (
    id          INTEGER PRIMARY KEY,                 -- 员工编号
    name        TEXT    NOT NULL,                    -- 姓名
    gender      TEXT    NOT NULL CHECK (gender IN ('男', '女')),
    dept_id     INTEGER NOT NULL REFERENCES departments(id),   -- 所在部门
    title       TEXT    NOT NULL,                    -- 职位
    salary      REAL    NOT NULL CHECK (salary > 0), -- 月薪（元）
    hire_date   TEXT    NOT NULL,                    -- 入职日期
    manager_id  INTEGER REFERENCES employees(id)     -- 直属上级的员工编号
);

