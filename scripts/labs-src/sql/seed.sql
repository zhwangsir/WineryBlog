-- ----------------------------------------------------------------------------
-- 项目分工表：40 行，记录「哪个员工在哪个项目里做什么」
-- 同一个员工在同一个项目里只出现一次；hours_per_week 是每周投入到这个项目的小时数
-- 5 位员工（编号 1、18、27、29、30）没有参与任何项目
-- ----------------------------------------------------------------------------
CREATE TABLE assignments (
    id             INTEGER PRIMARY KEY,
    employee_id    INTEGER NOT NULL REFERENCES employees(id),
    project_id     INTEGER NOT NULL REFERENCES projects(id),
    role           TEXT    NOT NULL,                 -- 在项目里承担的角色
    hours_per_week INTEGER NOT NULL CHECK (hours_per_week > 0),
    assigned_on    TEXT    NOT NULL,                 -- 加入项目的日期
    UNIQUE (employee_id, project_id)
);

