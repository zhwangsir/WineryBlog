-- ============================================================================
--  SQL 环境的默认练习数据库：星衡科技（一家虚构的软件公司）
--
--  数据快照时间：2025-06-30。共 4 张表，它们之间的关系是——
--
--    departments（部门）5 行
--        │ 1 个部门有多个员工，1 个员工只属于 1 个部门
--        ▼
--    employees（员工）30 行
--        │ 1 个员工可以被分派到多个项目，1 个项目也由多个员工共同完成
--        ▼
--    assignments（项目分工）40 行 ──────► projects（项目）8 行
--
--  说明：
--  · SQLite 没有专门的日期类型，日期统一用 TEXT 存成 'YYYY-MM-DD'，
--    这样按字符串比较大小、排序的结果和按日期比较完全一致。
--  · SQLite 默认不强制检查外键（需要执行 PRAGMA foreign_keys = ON 才检查），
--    这里的 FOREIGN KEY 用来说明表之间的关系；下面的数据本身是保持一致的。
--  · 右侧「练习库」面板里点表名可以随时查看表里的数据。
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 部门表：公司的 5 个部门
-- ----------------------------------------------------------------------------
CREATE TABLE departments (
    id          INTEGER PRIMARY KEY,                 -- 部门编号
    name        TEXT    NOT NULL UNIQUE,             -- 部门名称
    location    TEXT    NOT NULL,                    -- 所在城市
    manager_id  INTEGER REFERENCES employees(id),    -- 部门负责人的员工编号
    budget      REAL    NOT NULL                     -- 年度预算（万元）
);

