-- ============================================================================
-- SQL 查询基础：选列、起别名、去重、取前几行
-- 练习库是「星衡科技」的 4 张表，本示例只用 departments（部门）和 employees（员工）
-- 右上角的「运行」会把下面的 SQL 从上到下依次执行，每条 SELECT 的结果显示为一张表
-- 现在就点一次「运行」，看看右侧的结果；然后按左侧的步骤补全标着 TODO 的查询
-- ============================================================================

-- ── Step 1：选列与别名 ───────────────────────────────────────────────────────

-- 【查询 1】* 表示「所有列」：先看看公司有哪些部门
-- 预期：5 行 5 列：研发部 北京、产品部 北京、市场部 上海、人事部 北京、财务部 上海
SELECT * FROM departments;

-- 【查询 2】TODO：从 employees 表查出每个员工的 name、title、salary 三列，
--               并用 AS 给它们起中文别名：姓名、职位、月薪
-- 预期：30 行 3 列，表头显示为 姓名 | 职位 | 月薪

-- 【查询 3】AS 的左边可以是一个表达式：月薪 × 12 得到年薪
-- 预期：3 行 2 列：王振华 540000、李思远 456000、王强 384000
SELECT name AS 姓名, salary * 12 AS 年薪 FROM employees LIMIT 3;

-- ── Step 2：DISTINCT 去重 ───────────────────────────────────────────────────

-- 【查询 4】TODO：查询 departments 表的 location 一列，加上 DISTINCT 去掉重复行，
--               并用 AS 把这一列命名为 城市
-- 预期：2 行 1 列：北京、上海

-- 【查询 5】DISTINCT 作用于「选中的整行」：部门 + 性别的组合一共只有 10 种
-- （中文按字符编码排序，「女」排在「男」前面）
-- 预期：10 行 2 列：1 女、1 男、2 女、2 男、3 女、3 男、4 女、4 男、5 女、5 男
SELECT DISTINCT dept_id, gender FROM employees ORDER BY dept_id, gender;

-- ── Step 3：LIMIT 取前几行 ──────────────────────────────────────────────────

-- 【查询 6】TODO：查出月薪最高的 3 名员工的 name 和 salary
--               提示：先 ORDER BY salary DESC 排序，再用 LIMIT 3 只取前 3 行
-- 预期：3 行 2 列：王振华 45000、郑浩 40000、李思远 38000

-- 【查询 7】OFFSET：先跳过前 5 行，再取 5 行。列表页的「第 2 页」就是这样实现的
-- 预期：5 行 3 列：王强 2017-02-20、马婧 2017-05-08、韩露 2018-03-26、邓宇 2018-04-23、刘洋 2018-05-14
SELECT name, hire_date, salary FROM employees ORDER BY hire_date LIMIT 5 OFFSET 5;
