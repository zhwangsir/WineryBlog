say('开始');                                      // ① 同步代码
setTimeout(() => say('定时器'), 0);                // ④ 任务队列：等微任务全部清空后才轮到它
Promise.resolve().then(() => say('then'));        // ③ 微任务：同步代码一结束就执行
say('结束');                                      // ② 同步代码

// 顺序：开始 → 结束 → then → 定时器
// 每段同步代码执行完，引擎都会先把「微任务队列」清空，再去取「任务队列」里的下一个任务

